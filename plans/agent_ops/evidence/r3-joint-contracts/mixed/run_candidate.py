"""Run only copied candidate tests against the read-only qualified CI venv."""
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import sys
import time

HERE = Path(__file__).resolve().parent
ISOLATED = HERE / 'isolated'
attempt = sys.argv[1]
report_dir = HERE / 'reports' / attempt
report_dir.mkdir(parents=True, exist_ok=False)
profile = report_dir / 'profile'
for name in ('user', 'roaming', 'local'):
    (profile / name).mkdir(parents=True)
for key in tuple(os.environ):
    if key.startswith(('OKTO_', 'NEXUS_', 'OPENAI_', 'ANTHROPIC_', 'CLAUDE_', 'CODEX_',
                       'GOOGLE_', 'GEMINI_', 'AZURE_', 'AWS_', 'HF_', 'HUGGINGFACE_',
                       'COHERE_', 'MISTRAL_', 'GROQ_', 'HERDR_')) or key in ('PYTHONPATH', 'PYTHONHOME'):
        # Preserve the dedicated Codex runtime directory, never repurpose it.
        if key != 'CODEX_HOME':
            os.environ.pop(key, None)
os.environ['USERPROFILE'] = str(profile / 'user')
os.environ['APPDATA'] = str(profile / 'roaming')
os.environ['LOCALAPPDATA'] = str(profile / 'local')
os.chdir(ISOLATED)
sys.path[:0] = [str(ISOLATED / 'tests'), str(ISOLATED / 'tests' / 'execution_r4')]

versions = {name: importlib.metadata.version(name) for name in (
    'okto-nexus', 'okto-nexus-connector', 'okto-nexus-connector-core', 'mcp', 'pytest')}
assert versions['okto-nexus'] == '0.3.3'
assert versions['okto-nexus-connector'] == '0.0.12'
assert versions['okto-nexus-connector-core'] == '0.0.14'
assert versions['mcp'] == '1.30.0'
site = Path(sys.prefix).resolve() / 'Lib' / 'site-packages'
modules = {}

def guard():
    for name, module in tuple(sys.modules.items()):
        if not name.startswith(('okto_nexus', 'nexus_connector_core')):
            continue
        filename = getattr(module, '__file__', None)
        if filename:
            path = Path(filename).resolve()
            assert path.is_relative_to(site), f'Unexpected package origin: {name}'
            modules[name] = str(path)

import pytest

class ImportGuard:
    def pytest_runtest_teardown(self, item, nextitem):
        guard()

candidate = ISOLATED / 'tests' / 'execution_r4' / 'test_r3_mixed_coordination.py'
nodes = sys.argv[2:] or ['tests/execution_r4/test_r3_mixed_coordination.py']
args = [*nodes, '-q', '--tb=short', '-c', str(ISOLATED / 'pytest.ini'),
        '--junitxml', str(report_dir / 'tests.xml'), '--basetemp', str(report_dir / 'pytest-home')]
(report_dir / 'invocation.json').write_text(json.dumps({
    'python': sys.executable, 'isolated_python': bool(sys.flags.isolated),
    'versions': versions, 'pytest_args': args,
    'candidate_sha256': hashlib.sha256(candidate.read_bytes()).hexdigest(),
    'scope': 'Installed actual application/ASGI/MCP/SQLite/Core; native and installation discovery are explicit existing doubles.',
    'private_fixture_authentication': 'Ephemeral keys generated by the isolated canonical fixture, never user credentials.',
    'no_provider_or_registered_service': True,
}, indent=2) + '\n', encoding='utf-8')
started = time.monotonic()
exit_code = pytest.main(args, plugins=[ImportGuard()])
guard()
(report_dir / 'qualification.json').write_text(json.dumps({
    'exit_code': int(exit_code), 'elapsed_seconds': time.monotonic() - started,
    'versions': versions, 'loaded_package_modules': modules,
    'installed_modules_only': True, 'no_checkout_product_imports': True,
    'candidate_sha256': hashlib.sha256(candidate.read_bytes()).hexdigest(),
}, indent=2) + '\n', encoding='utf-8')
raise SystemExit(exit_code)
