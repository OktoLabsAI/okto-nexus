"""Persistence for authenticated operator remote setup, without transport authority."""
from typing import Protocol, Any


class RemoteSetupRepo(Protocol):
    def get(self, uow, *, actor: str, setup_run_id: str, revision: str | None = None) -> dict | None: ...
    def save_review(self, uow, *, actor: str, review: dict, request_hash: str,
                    expected_revision: str | None, now: str) -> None: ...
    def save_bootstrap(self, uow, *, actor: str, setup_run_id: str, revision: str,
                       receipt: dict, baseline: dict, now: str) -> None: ...
    def for_subject(self, uow, *, setup_run_id: str, agent_id: str) -> dict | None: ...
    def machine_review(self, uow, *, agent_id: str, connector_id: str) -> list[dict]: ...
    def server_id(self, uow) -> str: ...
    def baseline(self, uow, *, agent_id: str) -> dict: ...
    def credential(self, uow, *, agent_id: str, persist: bool) -> dict: ...
    def occupied_agent(self, uow, *, agent_id: str) -> bool: ...
    def materialization(self, uow, *, record: dict, proposal_id: str | None = None) -> dict[str, Any] | None: ...
